test('edits, excludes and restores energy records with persistence', async ({ page }) => {
  await addVehicle(page, '补能记录车', 'fuel')
  await addFuelRecord(page, '2026-08-20T10:00', '1500', '25', '125', true)
  await page.goto('/energy')

  const filter = page.getByLabel('补能记录筛选')
  await filter.selectOption('valid')
  await page.getByRole('button', { name: '编辑2026年8月20日加油记录' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑补能记录' })
  await dialog.getByLabel('金额（元）').fill('130')
  await dialog.getByRole('button', { name: '保存更改' }).click()
  await expect(page.getByRole('table', { name: '补能记录' })).toContainText('¥130.00')

  await page.getByRole('button', { name: '排除2026年8月20日加油记录' }).click()
  await expect(page.getByText('没有符合当前筛选的补能记录。')).toBeVisible()
  await filter.selectOption('excluded')
  await expect(page.getByRole('table', { name: '补能记录' })).toContainText('已排除')

  await page.reload()
  const excludedRow = page.getByRole('table', { name: '补能记录' }).getByRole('row').filter({ hasText: '2026年8月20日' })
  await expect(excludedRow).toContainText('已排除')
  await excludedRow.getByRole('button', { name: '恢复2026年8月20日加油记录' }).click()
  await expect(excludedRow).toContainText('参与计算')
  await page.reload()
  await expect(page.getByRole('table', { name: '补能记录' }).getByRole('row').filter({ hasText: '2026年8月20日' })).toContainText('参与计算')
})
