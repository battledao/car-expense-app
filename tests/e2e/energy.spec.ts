test('keeps the energy page usable without page overflow on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 480, height: 900 })
  await addVehicle(page, '窄屏测试车', 'fuel')
  await addFuelRecord(page, '2026-08-20T10:00', '1500', '25', '125', true)
  await page.goto('/energy')

  await expect(page.getByRole('heading', { name: '能耗统计' })).toBeVisible()
  await expect(page.getByLabel('能耗车辆')).toBeVisible()
  await expect(page.getByRole('table', { name: '补能记录' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  expect(await page.locator('.table-scroll').last().evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  expect(await page.locator('.energy-charts').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1)
})


